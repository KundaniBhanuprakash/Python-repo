n = int(input("Enter the no.of elements: "))
my_list = []
for i in range(n):
    value = int(input("Enter the values: "))
    my_list.append(value)
print(my_list)

print("Max element: ", max(my_list))
print("Min element: ", min(my_list))
print("sum of elements: ", sum(my_list))















